/**
 * Defender for Endpoint codegen (TDS 13, M6 / issue #7): IR sections → KQL
 * advanced-hunting queries. Covers Windows hosts where Sysmon deployment is
 * not permitted (and Linux hosts via Defender's Linux sensor).
 *
 *   mde/sbob/<name>_execs.kql     DeviceProcessEvents  (FolderPath allowlist)
 *   mde/sbob/<name>_opens.kql     DeviceFileEvents      (file-create partial)
 *   mde/sbob/<name>_egress.kql    DeviceNetworkEvents   (RemoteIP/RemotePort pairs)
 *
 * Semantics: each query returns drift rows — events whose subject is NOT in
 * the SBoB allowlist. Run them in advanced hunting (manual or scheduled) and
 * alert on a non-empty result set; Wazuh remains the aggregation SIEM.
 *
 * Documented v1 limitations (docs/engine-matrix.md):
 *   - execs[] args are not enforced (path-level);
 *   - opens[] is file-create telemetry only (the EID 11 / DeviceFileEvents
 *     partial, TDS 8.2) — read opens are invisible;
 *   - egress DNS names are not evaluable (DNS-NAME documented blind);
 *   - ingress[] has no DeviceNetworkEvents accept-side pair model in v1.
 */
import type { IR } from "../types.ts";
import type { BundleFile } from "./linux.ts";
import { engineManifest, pathGlob } from "./engines.ts";

function kqlString(s: string): string {
  return `"${s.replace(/"/g, '\\"')}"`;
}

export function generateMdeBundle(ir: IR): BundleFile[] {
  const files: BundleFile[] = [];
  const name = ir.workload.name;
  const notes: string[] = [];

  const header = (table: string, section: string) => [
    `// SBoB drift — ${name}: undeclared ${section} behavior`,
    `// generated by sbobctl transpile --target mde (TDS 13); rows = drift`,
    `// alert on a non-empty result set (advanced hunting / scheduled hunt)`,
    table,
  ];

  // execs -------------------------------------------------------------------
  if (ir.sections.execs) {
    const exact = ir.sections.execs.entries.filter((e) => e.isExact).map((e) => kqlString(e.source.path));
    const patterns = ir.sections.execs.entries.filter((e) => !e.isExact).map((e) => `FolderPath matches regex @"^${e.pathRegex}$"`);
    if (exact.length + patterns.length > 0) {
      const conds = [...(exact.length > 0 ? [`FolderPath in~ (${exact.join(", ")})`] : []), ...patterns];
      files.push({
        path: `mde/sbob/${name}_execs.kql`,
        content: [
          ...header("DeviceProcessEvents", "process execution (execs[])"),
          `| where not (${conds.join("\n  or ")})`,
          `| project Timestamp, DeviceName, FolderPath, ProcessCommandLine, AccountName`,
          `// args are not enforced (path-level filter) — the Wazuh bundle is args-precise`,
        ].join("\n") + "\n",
      });
    }
  } else {
    notes.push("mde: execs[] section absent — no process drift query emitted");
  }

  // opens — file-create partial ------------------------------------------------
  if (ir.sections.opens) {
    const exact = ir.sections.opens.entries.filter((e) => e.isExact).map((e) => kqlString(e.source.path));
    const patterns = ir.sections.opens.entries.filter((e) => !e.isExact).map((e) => `FolderPath matches regex @"^${e.pathRegex}$"`);
    if (exact.length + patterns.length > 0) {
      const conds = [...(exact.length > 0 ? [`FolderPath in~ (${exact.join(", ")})`] : []), ...patterns];
      files.push({
        path: `mde/sbob/${name}_opens.kql`,
        content: [
          ...header("DeviceFileEvents", "file create (opens[], file-create partial)"),
          `| where ActionType == "FileCreated"`,
          `| where not (${conds.join("\n  or ")})`,
          `| project Timestamp, DeviceName, FolderPath, FileName, InitiatingProcessFolderPath`,
          `// DeviceFileEvents carries file-create only — read/write-opens stay Wazuh's (TDS 8.2)`,
        ].join("\n") + "\n",
      });
    }
  } else {
    notes.push("mde: opens[] section absent — no file drift query emitted");
  }

  // egress — RemoteIP/RemotePort pairs ------------------------------------------
  if (ir.sections.egress) {
    const peers = ir.sections.egress.entries.filter((e) => e.addrEntries.length > 0);
    if (peers.length > 0) {
      const conds = peers.map((peer) => {
        const ips = peer.addrEntries.map((a) => kqlString(a.split("/")[0]!));
        const ports = peer.ports.filter((p): p is number => p !== null);
        const ipCond = `RemoteIP in~ (${ips.join(", ")})`;
        if (ports.length === 0) return ipCond;
        return `(${ipCond} and RemotePort in (${ports.join(", ")}))`;
      });
      files.push({
        path: `mde/sbob/${name}_egress.kql`,
        content: [
          ...header("DeviceNetworkEvents", "outbound connect (egress[])"),
          `| where ActionType == "ConnectionEstablished"`,
          `| where not (${conds.join("\n  or ")})`,
          `| project Timestamp, DeviceName, RemoteIP, RemotePort, InitiatingProcessFolderPath`,
          `// declared DNS names are not evaluable here (DNS-NAME documented blind)`,
        ].join("\n") + "\n",
      });
    }
    if (ir.sections.egress.entries.some((e) => e.dnsPatterns.length > 0 || e.dnsExact.length > 0)) {
      notes.push("mde: egress DNS names are not evaluable from DeviceNetworkEvents (DNS-NAME documented blind — Sigma EID 22 / Wazuh cover it)");
    }
  } else {
    notes.push("mde: egress[] section absent — no egress drift query emitted");
  }

  if (ir.sections.ingress) {
    notes.push("mde: ingress[] has no accept-side pair model in v1 — inbound connections are reported, not allowlist-evaluated (documented engine blind)");
  }

  notes.push(
    "mde: KQL is case-insensitive on in~/matches by design; wildcards use the sbobctl PCRE2 compilation via matches regex",
    "mde: covers hosts where Sysmon is not permitted; the Wazuh bundle remains the primary detector (TDS 13)",
  );

  engineManifest(ir, "mde", files, notes);
  return files;
}
